export const ICON_NAMES = Object.keys(PATHS) as readonly IconName[];

export type IconName = keyof typeof PATHS & string;

export interface IconProps {
  readonly name: IconName;
  readonly size?: number;
  readonly strokeWidth?: number;
  readonly color?: string;
  readonly style?: CSSProperties;
  readonly className?: string;
  readonly "aria-label"?: string;
}

export function Icon({
  name,
  size = 16,
  strokeWidth = 1.5,
  color = "currentColor",
  style,
  className,
  "aria-label": ariaLabel,
}: IconProps) {
  const paths = PATHS[name];
  if (!paths) return null;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      // Sem rótulo, o ícone é decorativo e não deve aparecer para leitores de tela — quem
      // carrega o significado é o texto ao lado, ou o `aria-label` do botão que o contém.
      aria-hidden={ariaLabel ? undefined : true}
      aria-label={ariaLabel}
      role={ariaLabel ? "img" : undefined}
      className={className}
      style={{ flexShrink: 0, ...style }}
    >
      {paths}
    </svg>
  );
}
